import { test, expect } from "@playwright/test";

const provider = "http://127.0.0.1:4373";

test("guest installs a legal add-on, saves its item, uses player controls and retains it on reload", async ({ page, context, browser }, testInfo) => {
  const pageErrors = [];
  page.on("pageerror", error => pageErrors.push(error.message));
  await context.route("**/*", async route => {
    if (["http://127.0.0.1:4371", provider].includes(new URL(route.request().url()).origin)) await route.continue();
    else await route.abort("blockedbyclient");
  });
  await context.addInitScript(() => {
    globalThis.__mvpBackEvents = [];
    window.addEventListener("popstate", event => globalThis.__mvpBackEvents.push({ route: event.state?.route, marker: event.state?.__nuvioHistory }));
    if (!localStorage.getItem("installedAddonUrls")) localStorage.setItem("installedAddonUrls", JSON.stringify({ __profileScoped: true, version: 1, profiles: { "1": [] } }));
  });
  await page.goto("/");
  await page.locator('[data-action="continueGuest"]').click();
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.locator('[data-focus-key="nav:contentDiscovery"]').click();
  await page.locator('[data-focus-key="contentDiscovery:addons"]').click();
  await page.locator("#desktop-addon-url").fill(`${provider}/basic/manifest.json`);
  await page.getByRole("button", { name: "Add Addon", exact: true }).click();
  await expect(page.locator(".settings-shell .desktop-addon-inline-status[role=status]")).toHaveCount(1);
  await expect(page.locator(".settings-shell .desktop-addon-inline-status[role=status]")).toHaveText("Saved locally");
  await page.getByRole("button", { name: "Home", exact: true }).click();
  await page.locator('#home .home-poster-card[data-item-id="fixture:original"]').first().click();
  await expect(page.getByRole("heading", { name: "Original Legal Fixture", exact: true })).toBeVisible();
  await page.locator('[data-action="toggleLibrary"]').click();
  await expect(page.locator('[data-action="toggleLibrary"]')).toHaveClass(/is-library-selected/);
  await page.locator('button[data-action="playDefault"]').click();
  await page.locator('[data-action="playStream"]').filter({ hasText: "Original local VP8/Opus" }).click();
  const video = page.locator("video");
  await expect.poll(() => video.evaluate(video => ({ width: video.videoWidth, height: video.videoHeight, error: video.error?.code || null }))).toEqual({ width: 640, height: 360, error: null });
  await expect.poll(() => video.evaluate(video => video.currentTime)).toBeGreaterThan(0.1);
  await page.mouse.move(640, 700);
  await page.locator('[data-action="playPause"]').click();
  await expect.poll(() => video.evaluate(video => video.paused)).toBe(true);
  const pausedAt = await video.evaluate(video => video.currentTime);
  const progress = page.locator("#playerProgressShell");
  const bounds = await progress.boundingBox();
  expect(bounds).not.toBeNull();
  await progress.click({ position: { x: bounds.width * 0.25, y: bounds.height / 2 } });
  const duration = await video.evaluate(video => video.duration);
  await expect.poll(() => video.evaluate(video => video.currentTime)).toBeCloseTo(duration * 0.25, 0);
  await page.locator('[data-action="subtitleDialog"]').click();
  const subtitles = page.locator("#playerSubtitleDialog");
  await expect(subtitles).toBeVisible();
  await subtitles.locator('[data-subtitle-rail="language"]').filter({ hasText: "English" }).click();
  await subtitles.locator('[data-subtitle-rail="options"]').first().click();
  await page.keyboard.press("Escape");
  await expect.poll(() => video.evaluate(video => Array.from(video.textTracks).filter(track => track.mode === "showing").flatMap(track => Array.from(track.activeCues || []).map(cue => cue.text)).join("\n"))).toMatch(/Original legal fixture|Second caption/);
  const subtitleState = await video.evaluate(video => Array.from(video.textTracks).map(track => ({ mode: track.mode, language: track.language, activeCues: Array.from(track.activeCues || []).map(cue => cue.text) })));
  await page.screenshot({ path: testInfo.outputPath("native-subtitle.png") });
  await page.locator('[data-action="playPause"]').click();
  await expect.poll(() => video.evaluate(video => video.paused)).toBe(false);
  await expect.poll(() => video.evaluate(video => video.currentTime)).toBeGreaterThan(duration * 0.25 + 0.1);
  await page.locator('[data-action="playPause"]').click();
  await expect.poll(() => video.evaluate(video => video.paused)).toBe(true);
  await page.mouse.move(640, 700);
  await page.locator('[data-action="audioTrack"]').click();
  const audio = page.locator("#playerAudioDialog");
  await expect(audio).toBeVisible();
  const audioDescription = await audio.innerText();
  await expect(audio.locator(".player-dialog-empty")).toHaveText("No audio tracks available.");
  await page.keyboard.press("Escape");
  await testInfo.attach("before-player-back", { body: JSON.stringify(await page.evaluate(() => ({ current: window.__NUVIO_CURRENT_ROUTE__, history: history.state, length: history.length }))), contentType: "application/json" });
  const expectedStreamIndex = await page.evaluate(() => history.state?.__nuvioHistory?.previousIndex);
  await page.locator("[data-player-desktop-back]").click();
  await expect.poll(() => page.evaluate(() => window.__NUVIO_CURRENT_ROUTE__)).toBe("stream");
  await expect.poll(() => page.evaluate(() => history.state?.__nuvioHistory?.index)).toBe(expectedStreamIndex);
  await expect(page.locator('[data-action="playStream"]')).toBeVisible();
  await testInfo.attach("before-stream-back", { body: JSON.stringify(await page.evaluate(() => ({ current: window.__NUVIO_CURRENT_ROUTE__, history: history.state, length: history.length, handler: String(document.querySelector('[data-stream-desktop-back]').onclick) }))), contentType: "application/json" });
  await page.locator("[data-stream-desktop-back]").click();
  await expect.poll(() => page.evaluate(() => ({ route: window.__NUVIO_CURRENT_ROUTE__, historyRoute: history.state?.route, marker: history.state?.__nuvioHistory, events: globalThis.__mvpBackEvents }))).toMatchObject({ route: "detail" });
  await expect(page.locator('[data-action="toggleLibrary"]')).toBeVisible();
  await page.locator("[data-detail-back]").click();
  await expect.poll(() => page.evaluate(() => window.__NUVIO_CURRENT_ROUTE__)).toBe("home");
  await expect(page.locator("#home")).toBeVisible();
  await page.getByRole("button", { name: "Library", exact: true }).click();
  await expect(page.locator('#library .library-grid-card[data-item-id="fixture:original"]')).toBeVisible();
  await page.reload();
  await page.locator('#profileSelection [data-profile-id="1"]').click();
  await page.getByRole("button", { name: "Skip setup", exact: true }).click();
  // The reload comes back to Library, with Home behind it.
  await expect(page.locator('#library .library-grid-card[data-item-id="fixture:original"]')).toBeVisible();
  await page.goBack();
  await expect(page.locator("#home")).toBeVisible();
  await expect(page.locator('#home .home-poster-card[data-item-id="fixture:original"]').first()).toBeVisible();
  expect(pageErrors).toEqual([]);
  await testInfo.attach("observed-mvp-playback", { body: JSON.stringify({ browser: browser.version(), environment: "headless Chromium on Linux ARM64", media: "CC0 original VP8/Opus 640x360", pausedAt, duration, subtitleState, audioDescription, limits: "Single audio fixture; audible output and track switching unverified. Synthetic local add-on, no hosted or real identity service." }), contentType: "application/json" });
});

test("source Back returns to detail both before and after opening the bundled player", async ({ page, context }, testInfo) => {
  await context.route("**/*", async route => {
    if (["http://127.0.0.1:4371", provider].includes(new URL(route.request().url()).origin)) await route.continue();
    else await route.abort("blockedbyclient");
  });
  await context.addInitScript(provider => {
    localStorage.setItem("installedAddonUrls", JSON.stringify({ __profileScoped: true, version: 1, profiles: { "1": [`${provider}/basic`] } }));
    globalThis.__mvpBackEvents = [];
    window.addEventListener("popstate", event => globalThis.__mvpBackEvents.push({ route: event.state?.route, marker: event.state?.__nuvioHistory }));
  }, provider);
  await page.goto("/");
  await page.locator('[data-action="continueGuest"]').click();
  await page.locator('#home .home-poster-card[data-item-id="fixture:original"]').first().click();
  await page.locator('button[data-action="playDefault"]').click();
  await page.locator("[data-stream-desktop-back]").click();
  await expect.poll(() => page.evaluate(() => window.__NUVIO_CURRENT_ROUTE__)).toBe("detail");
  await page.locator('button[data-action="playDefault"]').click();
  await page.locator('[data-action="playStream"]').click();
  await expect.poll(() => page.locator("video").evaluate(video => video.currentTime)).toBeGreaterThan(0.1);
  await page.locator('[data-action="playPause"]').click();
  await expect.poll(() => page.locator("video").evaluate(video => video.paused)).toBe(true);
  await page.locator("[data-player-desktop-back]").click();
  await expect.poll(() => page.evaluate(() => window.__NUVIO_CURRENT_ROUTE__)).toBe("stream");
  await testInfo.attach("before-returned-source-back", { body: JSON.stringify(await page.evaluate(() => ({ current: window.__NUVIO_CURRENT_ROUTE__, historyRoute: history.state?.route, marker: history.state?.__nuvioHistory, events: globalThis.__mvpBackEvents }))), contentType: "application/json" });
  await page.locator("[data-stream-desktop-back]").click();
  await expect.poll(() => page.evaluate(() => window.__NUVIO_CURRENT_ROUTE__)).toBe("detail");
});
